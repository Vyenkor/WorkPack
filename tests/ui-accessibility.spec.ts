import { _electron, expect, test } from '@playwright/test'
import fs from 'node:fs'
import os from 'node:os'
import path from 'node:path'
const electronExecutable = require('electron') as string

test('navigation, workspace menu, and storage settings follow the desktop layout', async ({}, info) => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'workpack-accessibility-'))
  const application = await _electron.launch({ executablePath: electronExecutable, args: ['.'], env: { ...process.env, WORKPACK_TEST_DATA: path.join(root, 'data') } })
  try {
    const page = await application.firstWindow()
    await expect(page.getByRole('heading', { name: '工作台' })).toBeVisible()
    await page.evaluate(() => document.fonts.ready)
    const fontSession = await page.context().newCDPSession(page)
    await fontSession.send('DOM.enable')
    await fontSession.send('CSS.enable')
    const domDocument = await fontSession.send('DOM.getDocument')
    const latinNode = await fontSession.send('DOM.querySelector', { nodeId: domDocument.root.nodeId, selector: '.global-search kbd' })
    const platformFonts = await fontSession.send('CSS.getPlatformFontsForNode', { nodeId: latinNode.nodeId })
    expect(platformFonts.fonts.some(font => font.isCustomFont && /Inter/.test(font.familyName))).toBe(true)
    await fontSession.detach()
    await expect(page.locator('body')).toHaveCSS('font-size', '15px')
    await expect(page.getByRole('button', { name: '新建项目' })).toHaveCSS('font-size', '13px')
    const nav = page.getByRole('navigation', { name: '主导航' })
    await expect(nav.locator('button')).toHaveCount(4)
    await expect(nav.getByRole('button', { name: '工作台' })).toHaveAttribute('aria-current', 'page')
    const footer = (await page.locator('.app-footer').boundingBox())!
    const emblem = (await page.locator('.footer-emblem').boundingBox())!
    expect(emblem.x - footer.x).toBe(24)
    expect(Math.abs(emblem.y + emblem.height / 2 - footer.y - footer.height / 2)).toBeLessThan(1)
    await expect(page.getByText('WorkPack', { exact: true })).toHaveCount(0)
    for (const icon of await nav.locator('svg.nav-icon').all()) {
      await expect(icon).toHaveAttribute('aria-hidden', 'true')
      await expect(icon).toHaveCSS('width', '16px')
    }
    const workspace = page.getByRole('button', { name: '我的工作空间' })
    await workspace.click()
    await expect(workspace).toHaveAttribute('aria-expanded', 'true')
    await expect(page.locator('.workspace-popover > button')).toHaveCount(2)
    await expect(page.getByRole('heading', { name: '最近更新' })).toHaveCount(0)
    const compactMenu = (await page.locator('.workspace-popover').boundingBox())!
    const triggerBox = (await workspace.boundingBox())!
    expect(compactMenu.x + compactMenu.width).toBeCloseTo(triggerBox.x + triggerBox.width, 3)
    expect(compactMenu.y).toBeCloseTo(triggerBox.y + triggerBox.height + 4, 3)
    expect(compactMenu.width).toBe(184)
    expect(compactMenu.height).toBeLessThanOrEqual(80)
    await page.screenshot({ path: info.outputPath('workspace-menu.png'), scale: 'css' })
    await page.keyboard.press('Tab')
    const news = page.getByRole('button', { name: 'News', exact: true })
    await expect(news).toBeFocused()
    await page.keyboard.press('Enter')
    await expect(page.getByRole('heading', { name: '最近更新' })).toBeVisible()
    await expect(page.getByRole('button', { name: '返回工作空间菜单' })).toBeFocused()
    await expect(page.locator('.whats-new li')).toHaveCount(4)
    await page.screenshot({ path: info.outputPath('workspace-news.png'), scale: 'css' })
    await page.keyboard.press('Escape')
    await expect(news).toBeFocused()
    await expect(workspace).toHaveAttribute('aria-expanded', 'true')
    await news.click()
    await page.getByRole('button', { name: '返回工作空间菜单' }).click()
    await expect(news).toBeFocused()
    await page.keyboard.press('Escape')
    await expect(workspace).toBeFocused()
    await expect(workspace).toHaveAttribute('aria-expanded', 'false')
    await workspace.click()
    await news.click()
    await page.getByRole('searchbox', { name: '搜索项目或客户' }).click()
    await expect(workspace).toHaveAttribute('aria-expanded', 'false')
    await workspace.click()
    await expect(news).toBeVisible()
    await expect(page.getByRole('heading', { name: '最近更新' })).toHaveCount(0)
    await page.getByRole('button', { name: '设置', exact: true }).click()
    await expect(page.getByRole('heading', { name: '设置' })).toBeVisible()
    await expect(page.locator('.storage-row')).toHaveCount(3)
    const migrationNotice = page.locator('.migration-notice')
    const noticeBox = (await migrationNotice.boundingBox())!
    expect(noticeBox.width).toBeCloseTo(720, 3)
    expect(noticeBox.height).toBeLessThanOrEqual(94)
    await expect(migrationNotice.locator('strong')).toHaveCSS('font-size', '13px')
    await expect(migrationNotice.locator('p').first()).toHaveCSS('font-size', '12px')
    const migrationDetails = migrationNotice.locator('details p')
    await expect(migrationDetails).toBeHidden()
    await migrationNotice.locator('summary').click()
    await expect(migrationDetails).toBeVisible()
    await expect(migrationDetails).toContainText('workpack-v3.sqlite')
    await migrationNotice.locator('summary').click()
    await expect(migrationDetails).toBeHidden()
    await page.screenshot({ path: info.outputPath('compact-migration-notice.png'), scale: 'css' })
    const popoverShadow = await page.locator('.workspace-popover').count()
    expect(popoverShadow).toBe(0)
    await nav.getByRole('button', { name: '文件库' }).click()
    await expect(nav.getByRole('button', { name: '文件库' })).toHaveAttribute('aria-current', 'page')
    await expect(page.getByRole('heading', { name: '文件库', exact: true })).toBeVisible()
    await page.getByRole('button', { name: '添加文件模板' }).click()
    await expect(page.locator('.modal-card')).toBeVisible()
    await expect(page.getByRole('textbox', { name: '文件名称' })).toBeFocused()
    await expect(page.locator('.modal-card')).toHaveCSS('border-top-left-radius', '12px')
    await page.keyboard.press('Escape')
    await expect(page.locator('.modal-card')).toHaveCount(0)
    await application.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setSize(1050, 700))
    const width = await page.evaluate(() => document.documentElement.scrollWidth)
    expect(width).toBeLessThanOrEqual(1050)
    for (const [width, height] of [[1050, 700], [1280, 800], [1600, 1000]]) {
      await application.evaluate(({ BrowserWindow }, size) => BrowserWindow.getAllWindows()[0].setContentSize(...size as [number, number]), [width, height])
      await workspace.click()
      const trigger = (await workspace.boundingBox())!
      for (const level of ['menu', 'news']) {
        if (level === 'news') await news.click()
        const popup = (await page.locator('.workspace-popover').boundingBox())!
        if (level === 'menu') expect(popup.x + popup.width).toBeCloseTo(trigger.x + trigger.width, 3)
        else expect(popup.x).toBeCloseTo(trigger.x, 3)
        expect(popup.y).toBeCloseTo(trigger.y + trigger.height + 4, 3)
        expect(popup.x).toBeGreaterThanOrEqual(0)
        expect(popup.x + popup.width).toBeLessThan(width)
        expect(popup.y + popup.height).toBeLessThan(height)
      }
      await page.keyboard.press('Escape')
      await page.keyboard.press('Escape')
    }
  } finally { await application.close(); fs.rmSync(root, { recursive: true, force: true }) }
})
