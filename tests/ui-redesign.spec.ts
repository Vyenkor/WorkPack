  await page.keyboard.press('ArrowDown'); await expect(page.getByRole('button', { name: '导入模板' })).toBeFocused()
  await page.keyboard.press('Escape'); await expect(page.getByRole('button', { name: '签收单操作' })).toBeFocused()
